package com.mnl.eduportal.util.reports;

/**
 *
 * @author eaglescan
 */
public class UploadReport {
    private String id;
    private String details;

    public UploadReport() {
    }

    public UploadReport(String id, String details) {
        this.id = id;
        this.details = details;
    }

    /**
     * @return the id
     */
    public String getId() {
        return id;
    }

    /**
     * @param id the id to set
     */
    public void setId(String id) {
        this.id = id;
    }

    /**
     * @return the details
     */
    public String getDetails() {
        return details;
    }

    /**
     * @param details the details to set
     */
    public void setDetails(String details) {
        this.details = details;
    }
    
}
